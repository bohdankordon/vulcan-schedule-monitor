ALTER TABLE notification_outbox
    ADD CONSTRAINT ck_notification_outbox_failure_category CHECK (
        last_failure_category IS NULL
        OR last_failure_category IN (
            'RETRYABLE', 'PERMANENT', 'UNEXPECTED', 'EXHAUSTED', 'UNROUTABLE'
        )
    );

UPDATE notification_outbox
SET status = 'DEAD',
    lease_until = NULL,
    claim_token = NULL,
    delivered_at = NULL,
    last_failure_category = 'UNROUTABLE'
WHERE recipient_user_id IS NULL
  AND status IN ('PENDING', 'IN_FLIGHT');

ALTER TABLE notification_outbox
    ADD CONSTRAINT ck_notification_outbox_actionable_recipient CHECK (
        status NOT IN ('PENDING', 'IN_FLIGHT') OR recipient_user_id IS NOT NULL
    );
